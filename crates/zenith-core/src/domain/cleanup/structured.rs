/// Cache containers whose extension says "database" but whose content is
/// regenerated on demand.
///
/// Windows Explorer keeps its thumbnail and icon caches in `.db` files
/// (`thumbcache_<size>.db`, `iconcache_<n>.db`). They are caches by contract —
/// Windows rebuilds them the next time it needs a picture — so treating the
/// extension alone as evidence of user state would protect a regenerable cache
/// and report its bytes as permanently unreclaimable. The list is deliberately
/// closed: a name that is not here is judged by the database rule, because the
/// cost of being wrong in that direction is a cache the user can still clear by
/// other means, not a database someone deletes.
const DISPOSABLE_CACHE_STORE_PREFIXES: [&str; 2] = ["thumbcache_", "iconcache_"];

const EXECUTABLE_EXTENSIONS: [&str; 17] = [
    "exe", "dll", "sys", "com", "scr", "msi", "msp", "bat", "cmd", "ps1", "sh", "zsh", "bash",
    "command", "dylib", "so", "o",
];

/// Credential directories, matched on the entry's own name.
const CREDENTIAL_DIRECTORIES: [&str; 7] = [
    ".ssh",
    ".gnupg",
    ".aws",
    ".azure",
    ".kube",
    "keychains",
    "credentials",
];

/// Classifies a path component as structured state, or returns `None`.
///
/// Names are compared case-insensitively on both platforms: Windows folds case
/// by definition, and a case-insensitive APFS volume can spell the same cache
/// name either way, so a case-sensitive rule would be a rule that admits the
/// object it exists to protect.
pub fn classify_structured_state(facts: PathFacts<'_>) -> Option<StructuredStateKind> {
    let name = facts.name.trim();
    if name.is_empty() {
        return None;
    }
    let lower = name.to_ascii_lowercase();
    let extension = lower
        .rsplit_once('.')
        .map(|(_, extension)| extension)
        .unwrap_or_default();

    if facts.entry_kind == EntryKind::Directory {
        if BUNDLE_EXTENSIONS.contains(&extension) {
            return Some(StructuredStateKind::ApplicationBundle);
        }
        if CREDENTIAL_DIRECTORIES.contains(&lower.as_str()) {
            return Some(StructuredStateKind::Credential);
        }
        return None;
    }

    // Companoins first: their base extension is what makes them companions, and
    // a name-shaped rule cannot tell a WAL from the database it belongs to.
    if COMPANION_SUFFIXES
        .iter()
        .any(|suffix| lower.ends_with(suffix))
    {
        return Some(StructuredStateKind::DatabaseCompanion);
    }
    if LOCK_NAMES.contains(&lower.as_str()) || LOCK_EXTENSIONS.contains(&extension) {
        return Some(StructuredStateKind::Lock);
    }
    if STORE_MARKERS.contains(&name) || lower.starts_with("manifest-") {
        return Some(StructuredStateKind::DatabaseCompanion);
    }
    if CREDENTIAL_NAMES.contains(&lower.as_str()) || CREDENTIAL_EXTENSIONS.contains(&extension) {
        return Some(StructuredStateKind::Credential);
    }
    if DISPOSABLE_CACHE_STORE_PREFIXES
        .iter()
        .any(|prefix| lower.starts_with(prefix))
    {
        // A cache container that happens to use a database extension. It is
        // still acted on only because a signature names it and its age policy
        // is satisfied; this rule decides that it is a cache, not that it is
        // disposable anywhere it appears.
        return None;
    }
    if DATABASE_EXTENSIONS.contains(&extension) {
        return Some(StructuredStateKind::Database);
    }
    if CONFIGURATION_NAMES.contains(&lower.as_str())
        || CONFIGURATION_EXTENSIONS.contains(&extension)
    {
        return Some(StructuredStateKind::Configuration);
    }
    if EXECUTABLE_EXTENSIONS.contains(&extension) || facts.executable {
        return Some(StructuredStateKind::Executable);
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    fn file(name: &str) -> Option<StructuredStateKind> {
        classify_structured_state(PathFacts::new(name, EntryKind::File))
    }

    fn directory(name: &str) -> Option<StructuredStateKind> {
        classify_structured_state(PathFacts::new(name, EntryKind::Directory))
    }

    #[test]
    fn databases_and_their_companions_are_protected() {
        assert_eq!(file("Cache.db"), Some(StructuredStateKind::Database));
        assert_eq!(file("cache.sqlite"), Some(StructuredStateKind::Database));
        assert_eq!(file("store.sqlite3"), Some(StructuredStateKind::Database));
        assert_eq!(file("000123.ldb"), Some(StructuredStateKind::Database));

        assert_eq!(
            file("Cache.db-wal"),
            Some(StructuredStateKind::DatabaseCompanion)
        );
        assert_eq!(
            file("cache.sqlite-shm"),
            Some(StructuredStateKind::DatabaseCompanion)
        );
        assert_eq!(
            file("history-journal"),
            Some(StructuredStateKind::DatabaseCompanion)
        );
        assert_eq!(
            file("MANIFEST-000004"),
            Some(StructuredStateKind::DatabaseCompanion)
        );
        assert_eq!(
            file("CURRENT"),
            Some(StructuredStateKind::DatabaseCompanion)
        );
    }

    #[test]
    fn locks_credentials_and_configuration_are_protected() {
        assert_eq!(file("app.lock"), Some(StructuredStateKind::Lock));
        assert_eq!(file("LOCK"), Some(StructuredStateKind::Lock));
        assert_eq!(file("service.pid"), Some(StructuredStateKind::Lock));

        assert_eq!(file("auth.json"), Some(StructuredStateKind::Credential));
        assert_eq!(
            file("login.keychain-db"),
            Some(StructuredStateKind::Credential)
        );
        assert_eq!(file("id_ed25519"), Some(StructuredStateKind::Credential));
        assert_eq!(directory(".ssh"), Some(StructuredStateKind::Credential));

        assert_eq!(
            file("com.example.app.plist"),
            Some(StructuredStateKind::Configuration)
        );
        assert_eq!(
            file("settings.json"),
            Some(StructuredStateKind::Configuration)
        );
    }

    #[test]
    fn bundles_and_executables_are_protected() {
        assert_eq!(
            directory("Google Chrome for Testing.app"),
            Some(StructuredStateKind::ApplicationBundle)
        );
        assert_eq!(
            directory("Some.framework"),
            Some(StructuredStateKind::ApplicationBundle)
        );
        assert_eq!(file("setup.exe"), Some(StructuredStateKind::Executable));
        assert_eq!(file("libfoo.dylib"), Some(StructuredStateKind::Executable));

        // An executable bit with an unremarkable name is still an executable.
        assert_eq!(
            classify_structured_state(PathFacts::new("helper", EntryKind::File).executable(true)),
            Some(StructuredStateKind::Executable)
        );
        assert_eq!(
            classify_structured_state(PathFacts::new("helper", EntryKind::File)),
            None
        );
    }

    /// A cache container is not a database, however its extension reads.
    #[test]
    fn explorer_thumbnail_and_icon_caches_are_caches_not_databases() {
        for name in ["thumbcache_256.db", "THUMBCACHE_1024.DB", "iconcache_48.db"] {
            assert_eq!(file(name), None, "{name} is a regenerable cache");
        }

        // The exception is closed: any other `.db` is still structured state,
        // and the prefix has to be the whole leading name.
        for name in ["history.db", "places.sqlite", "my-thumbcache.db"] {
            assert_eq!(
                file(name),
                Some(StructuredStateKind::Database),
                "{name} is not one of the cache containers"
            );
        }
        // A name with no database extension was never protected by that rule.
        assert_eq!(file("thumbcache"), None);
    }

    #[test]
    fn case_is_folded_because_a_volume_may_fold_it_too() {
        assert_eq!(file("CACHE.DB"), Some(StructuredStateKind::Database));
        assert_eq!(file("Auth.JSON"), Some(StructuredStateKind::Credential));
        assert_eq!(
            directory("Something.APP"),
            Some(StructuredStateKind::ApplicationBundle)
        );
    }

    /// The classifier is the boundary that keeps a generic rule out of
    /// structured state, so ordinary cache and log shapes must stay clean.
    #[test]
    fn ordinary_cache_and_log_shapes_are_not_structured_state() {
        for name in [
            "com.spotify.client",
            "Cache_Data",
            "Code Cache",
            "GPUCache",
            "ShaderCache",
            "CacheStorage",
            "Service Worker",
            "logs",
            "session.log",
            "trace.json",
        ] {
            assert_eq!(
                directory(name),
                None,
                "{name} must not classify as a bundle"
            );
            assert_eq!(file(name), None, "{name} must not classify as a file kind");
        }
    }

    #[test]
    fn an_empty_name_is_never_a_verdict() {
        assert_eq!(file(""), None);
        assert_eq!(file("   "), None);
        assert_eq!(directory(""), None);
    }
}
