//! Which paths hold state that generic cleanup must never treat as junk.
//!
//! An age rule answers "has anything in here changed recently?". That is a
//! question about caches and logs, and it is the wrong question for a database,
//! a credential store, an application bundle, or a lock file: those are
//! structured, they are frequently written by other processes, and removing one
//! of them costs the user data rather than cache warmth. A generic rule that
//! deleted them would be deleting the only copy of something.
//!
//! The classification is deliberately pure and name-shaped: it is the *shared*
//! rule both platforms and both boundaries (planning and execution) agree on,
//! and it cannot depend on a filesystem cache or on a platform API without
//! making an unprovable decision possible. The caller supplies the two facts
//! that are not in the name — whether the entry is a directory and whether it
//! is marked executable — because those come from metadata the platform layer
//! already read.
//!
//! This is a boundary, not a policy. A signature that legitimately owns a
//! disposable database would have to go through a specialized provider (its own
//! lifecycle, its own verification); nothing about a discovery rule may reach
//! past this classifier.

use serde::{Deserialize, Serialize};

/// What kind of structured state a path name identifies.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "snake_case")]
pub enum StructuredStateKind {
    /// A database file (`*.sqlite`, `*.db`, `*.realm`, LevelDB tables).
    Database,
    /// A file that only means something alongside a database: write-ahead logs,
    /// shared-memory files, journals, and LevelDB manifests.
    DatabaseCompanion,
    /// A lock, lease, or pid file: evidence that something else is using the
    /// location right now.
    Lock,
    /// Credentials, keys, tokens, and the directories that hold them.
    Credential,
    /// Configuration and preference state that outlives the cache around it.
    Configuration,
    /// An application, framework, or library bundle: an installable object.
    ApplicationBundle,
    /// An executable image.
    Executable,
}

impl StructuredStateKind {
    /// The reason shown when this classification blocks a cleanup.
    pub fn display_name(&self) -> &'static str {
        match self {
            Self::Database => "database file",
            Self::DatabaseCompanion => "database companion file",
            Self::Lock => "lock or pid file",
            Self::Credential => "credential or key material",
            Self::Configuration => "configuration state",
            Self::ApplicationBundle => "application bundle",
            Self::Executable => "executable image",
        }
    }

    /// Whether the entry holds state that cannot be regenerated by the owner.
    pub fn is_irreplaceable(&self) -> bool {
        matches!(self, Self::Credential | Self::Configuration)
    }
}

/// The entry kind the caller observed, as far as the shared rule needs it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "snake_case")]
pub enum EntryKind {
    #[default]
    File,
    Directory,
    /// Neither a regular file nor a directory: a socket, a fifo, a device.
    Other,
}

/// The facts the classifier is allowed to use.
#[derive(Debug, Clone, Copy)]
pub struct PathFacts<'a> {
    /// The final path component, as the filesystem spells it.
    pub name: &'a str,
    pub entry_kind: EntryKind,
    /// Whether the platform marked the entry executable (POSIX mode bit, or a
    /// Windows executable image). A name alone cannot say this.
    pub executable: bool,
}

impl<'a> PathFacts<'a> {
    pub fn new(name: &'a str, entry_kind: EntryKind) -> Self {
        Self {
            name,
            entry_kind,
            executable: false,
        }
    }

    pub fn executable(mut self, executable: bool) -> Self {
        self.executable = executable;
        self
    }
}

